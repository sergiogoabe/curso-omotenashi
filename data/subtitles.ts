export interface SubtitleEntry {
  start: number
  end: number
  text: string
}

function make(start: number, text: string): SubtitleEntry {
  const duration = text.length < 50 ? 3 : text.length < 80 ? 4 : 5
  return { start, end: start + duration, text }
}

function seq(entries: string[]): SubtitleEntry[] {
  const result: SubtitleEntry[] = []
  let t = 2
  for (const text of entries) {
    const duration = text.length < 50 ? 3 : text.length < 80 ? 4 : 5
    result.push({ start: t, end: t + duration, text })
    t += duration + 0.5
  }
  return result
}

